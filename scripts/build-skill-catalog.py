#!/usr/bin/env python3
"""Generate a public index from tracked and non-ignored skill folders."""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
FRONTMATTER = re.compile(r"^---\r?\n(.*?)\r?\n---\r?\n?", re.DOTALL)
OUTPUT = ROOT / "docs" / "SKILL_CATALOG.md"


def git_visible_skill_paths() -> dict[str, Path]:
    result = subprocess.run(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard", "-z"],
        cwd=ROOT,
        check=True,
        capture_output=True,
    )
    paths = result.stdout.decode("utf-8").split("\0")
    skills: dict[str, Path] = {}
    for raw_path in paths:
        if not raw_path or not raw_path.endswith("/SKILL.md"):
            continue
        relative = Path(raw_path)
        if not (ROOT / relative).is_file():
            continue
        if len(relative.parts) != 2 or relative.parts[0].startswith("."):
            continue
        skills[relative.parts[0]] = ROOT / relative
    return dict(sorted(skills.items()))


def parse_metadata(path: Path) -> dict[str, str]:
    match = FRONTMATTER.match(path.read_text(encoding="utf-8"))
    if not match:
        raise ValueError(f"{path.relative_to(ROOT)} is missing YAML frontmatter")

    metadata: dict[str, str] = {}
    for line in match.group(1).splitlines():
        if line.startswith((" ", "\t")) or ":" not in line:
            continue
        key, value = line.split(":", 1)
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        metadata[key.strip()] = value.replace("\\\"", '"').strip()
    return metadata


def render_catalog() -> str:
    skills = git_visible_skill_paths()
    if not skills:
        raise ValueError("No Git-visible skill folders were found")

    grouped: dict[str, list[tuple[str, str]]] = {}
    for folder, path in skills.items():
        metadata = parse_metadata(path)
        name = metadata.get("name", "")
        description = metadata.get("description", "")
        if name != folder or not description:
            raise ValueError(f"{path.relative_to(ROOT)} has a mismatched name or empty description")
        description = re.sub(r"\s+", " ", description).replace("[", "\\[").replace("]", "\\]")
        initial = folder[0].upper()
        grouped.setdefault(initial, []).append((folder, description))

    lines = [
        "# Skill Catalog",
        "",
        "Alphabetical index of skill folders visible to Git. Read the linked `SKILL.md`",
        "before using a workflow; it defines the activation boundary, required tools,",
        "fallbacks, and verification steps.",
        "",
        f"**{len(skills)} skills** are listed. This file is generated by",
        "`scripts/build-skill-catalog.py`.",
        "",
    ]
    for initial, entries in grouped.items():
        lines.extend([f"## {initial}", ""])
        for name, description in entries:
            lines.append(f"- [`{name}`](../{name}/SKILL.md) — {description}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the generated index is stale")
    args = parser.parse_args()

    try:
        generated = render_catalog()
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else None
        if args.check:
            if current != generated:
                print(json.dumps({"status": "stale", "path": "docs/SKILL_CATALOG.md"}))
                return 1
            print(json.dumps({"status": "ok", "skills": len(git_visible_skill_paths())}))
            return 0
        if current != generated:
            OUTPUT.write_text(generated, encoding="utf-8", newline="\n")
            status = "written"
        else:
            status = "unchanged"
        print(json.dumps({"status": status, "skills": len(git_visible_skill_paths())}))
        return 0
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print(json.dumps({"status": "failed", "error": str(error)}))
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
